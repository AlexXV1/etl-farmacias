-- 04_dw.sql — Modelo dimensional (esquema estrella).
--
--                  dim_fecha
--                      |
--   dim_territorio — fact_establecimiento_diario — dim_establecimiento
--
-- GRANO del hecho: un establecimiento observado en una fecha (snapshot periódico diario).

-- Dimensión de tiempo: fecha de OBSERVACIÓN (día de la extracción), porque la API solo entrega
-- el día actual y la "fecha" de la fuente no es confiable (formatos distintos, turnos antiguos).
CREATE TABLE IF NOT EXISTS dw.dim_fecha (
    fecha_id          integer  PRIMARY KEY,          -- AAAAMMDD (clave inteligente, legible)
    fecha             date     NOT NULL UNIQUE,
    anio              smallint NOT NULL,
    trimestre         smallint NOT NULL CHECK (trimestre BETWEEN 1 AND 4),
    mes               smallint NOT NULL CHECK (mes BETWEEN 1 AND 12),
    nombre_mes        text     NOT NULL,
    dia               smallint NOT NULL CHECK (dia BETWEEN 1 AND 31),
    dia_semana_iso    smallint NOT NULL CHECK (dia_semana_iso BETWEEN 1 AND 7),
    nombre_dia        text     NOT NULL,
    es_fin_de_semana  boolean  NOT NULL
);

-- Se pobla una vez con generate_series; ON CONFLICT la hace idempotente.
-- Ojo: la serie se genera como timestamp SIN zona horaria. Con DATE a secas PostgreSQL usa
-- timestamptz, y en America/Santiago la medianoche del cambio de hora (p. ej. 2026-09-06) no
-- existe: la serie pasa a las 01:00 y el último día (2030-12-31) queda fuera del rango.
INSERT INTO dw.dim_fecha
SELECT to_char(d, 'YYYYMMDD')::integer,
       d::date,
       extract(year FROM d)::smallint,
       extract(quarter FROM d)::smallint,
       extract(month FROM d)::smallint,
       (ARRAY['enero','febrero','marzo','abril','mayo','junio','julio','agosto',
              'septiembre','octubre','noviembre','diciembre'])[extract(month FROM d)::int],
       extract(day FROM d)::smallint,
       extract(isodow FROM d)::smallint,
       (ARRAY['lunes','martes','miércoles','jueves','viernes','sábado','domingo'])[extract(isodow FROM d)::int],
       extract(isodow FROM d) IN (6, 7)
FROM generate_series(TIMESTAMP '2026-01-01', TIMESTAMP '2030-12-31', INTERVAL '1 day') AS d
ON CONFLICT (fecha_id) DO NOTHING;

-- Dimensión territorial (comuna -> provincia -> región). Clave natural: CUT SUBDERE.
CREATE TABLE IF NOT EXISTS dw.dim_territorio (
    territorio_sk   smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,   -- clave subrogada
    cut_com         char(5)     NOT NULL UNIQUE,                             -- clave natural
    comuna          text        NOT NULL,
    cut_prov        char(3)     NOT NULL,
    provincia       text        NOT NULL,
    cut_reg         char(2)     NOT NULL,
    region          text        NOT NULL,
    vigente         boolean     NOT NULL DEFAULT true,
    actualizado_en  timestamptz NOT NULL DEFAULT now()
);
-- Miembro 0: establecimientos sin correspondencia territorial confiable. Permite conservarlos
-- en el hecho (y contarlos) sin inventarles una comuna ni perderlos con un INNER JOIN.
INSERT INTO dw.dim_territorio (territorio_sk, cut_com, comuna, cut_prov, provincia, cut_reg, region, vigente)
VALUES (0, '00000', 'Sin correspondencia', '000', 'Sin correspondencia', '00', 'Sin correspondencia', false)
ON CONFLICT (territorio_sk) DO NOTHING;

-- Dimensión establecimiento (SCD tipo 1: se sobrescriben los atributos con el valor más reciente;
-- la presencia diaria y la comuna de cada día quedan registradas en el hecho).
CREATE TABLE IF NOT EXISTS dw.dim_establecimiento (
    establecimiento_sk    integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,  -- clave subrogada
    local_id              integer     NOT NULL UNIQUE,                       -- clave natural MINSAL
    nombre                text        NOT NULL,
    tipo_establecimiento  text        NOT NULL,
    direccion             text,
    telefono              text,
    localidad             text,
    latitud               numeric(10, 7),
    longitud              numeric(10, 7),
    primera_observacion   date        NOT NULL,
    ultima_observacion    date        NOT NULL,     -- si deja de aparecer, esta fecha deja de avanzar
    actualizado_en        timestamptz NOT NULL DEFAULT now(),
    CHECK (ultima_observacion >= primera_observacion)
);

-- Tabla de hechos. Medida implícita: conteo (cada fila = 1 establecimiento ese día);
-- los booleanos permiten contar subconjuntos (turno, turno vigente, coordenada válida).
CREATE TABLE IF NOT EXISTS dw.fact_establecimiento_diario (
    fecha_id                integer  NOT NULL REFERENCES dw.dim_fecha (fecha_id),
    establecimiento_sk      integer  NOT NULL REFERENCES dw.dim_establecimiento (establecimiento_sk),
    territorio_sk           smallint NOT NULL REFERENCES dw.dim_territorio (territorio_sk),
    en_listado_general      boolean  NOT NULL,
    en_turno                boolean  NOT NULL,
    turno_vigente           boolean  NOT NULL DEFAULT false,
    coordenada_valida       boolean  NOT NULL,
    estado_correspondencia  text     NOT NULL,
    cargado_en              timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (fecha_id, establecimiento_sk)    -- garantiza el grano: no hay duplicados por día
);

CREATE INDEX IF NOT EXISTS ix_fact_fecha_territorio
    ON dw.fact_establecimiento_diario (fecha_id, territorio_sk);

COMMENT ON TABLE dw.fact_establecimiento_diario IS
    'Grano: 1 fila por establecimiento observado por fecha. Medida implícita: conteo (cada fila = 1 establecimiento).';
